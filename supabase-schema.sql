create table if not exists public.businesses (
  id bigint generated by default as identity primary key,
  slug_url text not null unique check (slug_url ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null,
  whatsapp_phone text not null,
  business_description text,
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  name text not null,
  description text,
  price numeric(12, 2),
  duration_minutes integer,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses(id) on delete cascade,
  service_id bigint references public.services(id) on delete set null,
  customer_name text not null,
  customer_phone text,
  requested_date date,
  requested_time time,
  detail text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists services_business_id_idx on public.services (business_id);
create index if not exists bookings_business_id_created_at_idx on public.bookings (business_id, created_at desc);

alter table public.businesses enable row level security;
alter table public.services enable row level security;
alter table public.bookings enable row level security;

drop policy if exists "Public can read businesses" on public.businesses;
create policy "Public can read businesses"
on public.businesses for select
using (true);

drop policy if exists "Public can create businesses" on public.businesses;
create policy "Public can create businesses"
on public.businesses for insert
with check (true);

drop policy if exists "Public can update businesses" on public.businesses;
create policy "Public can update businesses"
on public.businesses for update
using (true)
with check (true);

drop policy if exists "Public can read active services" on public.services;
create policy "Public can read active services"
on public.services for select
using (active = true);

drop policy if exists "Public can create bookings" on public.bookings;
create policy "Public can create bookings"
on public.bookings for insert
with check (
  exists (
    select 1
    from public.businesses b
    where b.id = business_id
  )
);
